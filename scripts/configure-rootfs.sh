#!/usr/bin/env bash
# Apply only Gemini-specific customizations to an Armbian root filesystem.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source "$ROOT/scripts/env.sh"
ROOTFS="${ROOTFS:-$OUT/rootfs}"
[[ $EUID == 0 ]] || { echo 'Run inside the build container or as root.' >&2; exit 1; }
[[ -x "$ROOTFS/usr/lib/systemd/systemd" ]] || { echo 'Missing systemd rootfs' >&2; exit 1; }
[[ -f "$ROOTFS/etc/armbian-release" ]] || {
    echo 'Expected an Armbian framework rootfs; refusing to relabel a Debian bootstrap.' >&2; exit 1;
}
[[ -d "$OUT/modules/lib/modules" && -d "$OUT/utilities" ]] || {
    echo 'Build kernel and board utilities first' >&2; exit 1;
}

# Service suppression is only for image construction, never the installed OS.
python3 "$ROOT/scripts/rootfs_service_policy.py" "$ROOTFS"

# Guard against reintroducing files which shadow the distro ABI or identity.
for path in usr/lib/aarch64-linux-gnu usr/sbin usr/bin/wpa_passphrase etc/armbian-release; do
    [[ ! -e "$ROOT/rootfs-overlay/$path" ]] || { echo "Forbidden overlay: $path" >&2; exit 1; }
done
rsync -aK --exclude=__pycache__/ --chown=0:0 "$ROOT/rootfs-overlay/" "$ROOTFS/"
python3 "$ROOT/scripts/prepare-wifi-board.py" --destination-root "$ROOTFS"
python3 - "$ROOTFS/usr/local/lib/mi5" <<'PY'
import pathlib, shutil, sys
for path in pathlib.Path(sys.argv[1]).rglob('__pycache__'):
    if path.is_dir():
        shutil.rmtree(path)
PY
# The CLI and SSH interface use one tested UTF-8 English locale.
if ! chroot "$ROOTFS" /usr/bin/locale -a | grep -qx 'en_US.utf8'; then
    sed -i 's/^# *en_US.UTF-8 UTF-8/en_US.UTF-8 UTF-8/' "$ROOTFS/etc/locale.gen"
    chroot "$ROOTFS" /usr/sbin/locale-gen en_US.UTF-8
fi
chroot "$ROOTFS" /usr/sbin/update-locale --reset LANG=en_US.UTF-8 LANGUAGE=en_US:en LC_MESSAGES=en_US.UTF-8
install -D -m644 "$ROOT/config/project.json" "$ROOTFS/usr/share/mi5/project.json"
mkdir -p "$ROOTFS/etc/issue.d"
printf '%s\n' 'Armbian for Xiaomi Mi 5 (community)' 'LCD console | Run mi5-config for device settings' > "$ROOTFS/etc/issue.d/20-mi5.issue"
rsync -aK --chown=0:0 "$OUT/utilities/" "$ROOTFS/"
systemd-sysusers --root="$ROOTFS"
mkdir -p "$ROOTFS/usr/lib/modules"
rsync -a --delete --chown=0:0 "$OUT/modules/lib/modules/" "$ROOTFS/usr/lib/modules/"
for dir in "$OUT/modules/lib/modules/"*; do
    krel="${dir##*/}"
    # modules_install links refer to the builder; headers are not shipped.
    for name in build source; do
        link="$ROOTFS/usr/lib/modules/$krel/$name"
        [[ ! -L "$link" ]] || rm -f -- "$link"
    done
    depmod -b "$ROOTFS" "$krel"
done
chmod 755 "$ROOTFS/usr/local/sbin/"*
printf 'gemini-rootfs-v1\n' > "$ROOTFS/etc/gemini-rootfs"
printf 'mi5-armbian\n' > "$ROOTFS/etc/hostname"
cat > "$ROOTFS/etc/hosts" <<'EOF'
127.0.0.1 localhost
127.0.1.1 mi5-armbian
::1 localhost ip6-localhost ip6-loopback
EOF
cat > "$ROOTFS/etc/fstab" <<'EOF'
/dev/disk/by-partlabel/userdata / ext4 defaults,noatime,errors=remount-ro 0 1
tmpfs /tmp tmpfs defaults,nodev,nosuid 0 0
EOF

mkdir -p "$ROOTFS/etc/NetworkManager/conf.d" "$ROOTFS/mnt/storage"
# Remove the priority file generated by the project's older Ethernet-first
# configurator; its later filename would override the new Wi-Fi defaults.
rm -f "$ROOTFS/etc/NetworkManager/conf.d/20-wired-priority.conf"
# Network priority defaults are supplied by the board overlay. NetworkManager
# handles reconnection and route withdrawal; the legacy gateway-ping watchdog
# must not cycle the primary Wi-Fi radio during an upstream/ICMP outage.
rm -f "$ROOTFS/etc/systemd/system/multi-user.target.wants/mi5-network-watchdog.service"
ln -sfn /dev/null "$ROOTFS/etc/systemd/system/mi5-network-watchdog.service"
mkdir -p "$ROOTFS/etc/systemd/system/multi-user.target.wants" \
    "$ROOTFS/etc/systemd/system/getty.target.wants"
mkdir -p "$ROOTFS/etc/systemd/system/timers.target.wants"
ln -sfn ../mi5-health.timer "$ROOTFS/etc/systemd/system/timers.target.wants/mi5-health.timer"
for service in gemini-resize-root gemini-ssh-hostkeys mi5-console mi5-usb-gadget mi5-usb-dhcp; do
    ln -sfn "../$service.service" "$ROOTFS/etc/systemd/system/multi-user.target.wants/$service.service"
done
for target in multi-user graphical; do
    rm -f "$ROOTFS/etc/systemd/system/$target.target.wants/display-unblank.service" \
        "$ROOTFS/etc/systemd/system/$target.target.wants/gemini-fb-ui.service"
done
rm -f "$ROOTFS/etc/systemd/system/multi-user.target.wants/gemini-server-mode.service"
ln -sfn ../gemini-server-mode.service \
    "$ROOTFS/etc/systemd/system/multi-user.target.wants/gemini-server-mode.service"
ln -sfn /lib/systemd/system/getty@.service \
    "$ROOTFS/etc/systemd/system/getty.target.wants/getty@tty1.service"
for target in multi-user sysinit; do
    rm -f "$ROOTFS/etc/systemd/system/$target.target.wants/usb-gadget-rndis.service"
done
ln -sfn /dev/null "$ROOTFS/etc/systemd/system/usb-gadget-rndis.service"
for service in armbian-zram-config armbian-ramlog; do
    ln -sfn "/lib/systemd/system/$service.service" "$ROOTFS/etc/systemd/system/multi-user.target.wants/$service.service"
done
# The standard SBC resize service may edit a partition table. Android's GPT
# must stay intact; gemini-resize-root only grows ext4 inside userdata.
ln -sfn /dev/null "$ROOTFS/etc/systemd/system/armbian-resize-filesystem.service"
for service in ssh NetworkManager; do
    ln -sfn "/lib/systemd/system/$service.service" "$ROOTFS/etc/systemd/system/multi-user.target.wants/$service.service"
done
ln -sfn /lib/systemd/system/serial-getty@.service \
    "$ROOTFS/etc/systemd/system/getty.target.wants/serial-getty@ttyGS0.service"
# Host modem probes must not enter the root first-login wizard. Keep normal
# authenticated USB getty; the LCD still offers Armbian's local onboarding.
rm -f "$ROOTFS/etc/systemd/system/serial-getty@.service.d/override.conf" \
    "$ROOTFS/etc/systemd/system/serial-getty@ttyGS0.service.d/override.conf"
for service in gdm gdm3 display-manager plymouth-start plymouth-quit plymouth-quit-wait \
    plymouth-reboot plymouth-halt plymouth-poweroff plymouth-kexec; do
    ln -sfn /dev/null "$ROOTFS/etc/systemd/system/$service.service"
done

# Until its charge-only control has been corrected and verified on the phone,
# do not enable the old guard which suspends USB input power at the threshold.
ln -sfn /dev/null "$ROOTFS/etc/systemd/system/mi5-power-guard.service"
# Do not ship host identity or the builder's authorized keys.
rm -f "$ROOTFS"/etc/ssh/ssh_host_* "$ROOTFS/etc/gemini-root-password"
find "$ROOTFS/root" "$ROOTFS/home" -name authorized_keys -delete
truncate -s 0 "$ROOTFS/etc/machine-id"
rm -f "$ROOTFS/var/lib/NetworkManager/secret_key"
rm -f "$ROOTFS/var/lib/dbus/machine-id"
ln -s /etc/machine-id "$ROOTFS/var/lib/dbus/machine-id"
echo 'Gemini customization complete; Armbian owns user onboarding and credentials.'
